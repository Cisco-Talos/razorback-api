static unsigned handlerCount = 0;
handlerNode *head = NULL;

static HRESULT addHandler(handler_fp fp)
{
    handlerNode *newNode;

    newNode = malloc(sizeof(*newNode));
    if (newNode == NULL)
        return R_MALLOC_FAIL;

    newNode->fp = fp;
    newNode->next = head;
    head = newNode;

    return R_SUCCESS;
}

static HRESULT updateNugget(const uuid_t nugtype, const uuid_t nugapp, const uuid_t datatype,
                            unsigned short nugport, unsigned nugid)
{
    //Connect to Dispatch Server
    RZBNetworkConnection *net = ConnectMe(rzbconfig.dsrvaddr, rzbconfig.dsrvport);
    if (!net)
    {
        rzb_log(LOG_ERR, "connection to %s:%s failed", rzbconfig.dsrvaddr, rzbconfig.dsrvport);
        return R_FAIL;
    }

    //Set up packet format to send
    SNAKECHARMER scpacket;
    NEWCAPPACKET newcap;
    protocolFill(&scpacket);
    uuid_copy(scpacket.datatype, nugtype);
    scpacket.msgtype = NEWCAP;

    /* Build Registration Packet */
    /* Nugget Network Info */
    newcap.nuggetid = nugid;
    inet_pton(AF_INET, rzbconfig.nugaddr, &newcap.nugaddr);
    newcap.nugport = nugport;

    /* Capability Declaration */
    uuid_copy(newcap.nugtype, nugtype);
    uuid_copy(newcap.nugapp, nugapp);
    uuid_copy(newcap.datatype, datatype);

    //Send packet
    if (sendWrap(net, &scpacket, sizeof(scpacket)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        return R_FAIL;
    }

    if (sendWrap(net, &newcap, sizeof(newcap)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        return R_FAIL;
    }

    //Recv ACK (hopefully)
    if (recvWrap(net, &scpacket, sizeof(scpacket)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        return R_FAIL;
    }

    NetworkConnectionDestroy(net);
    return R_SUCCESS;
}

static HRESULT registerNugget(const uuid_t nugtype, const uuid_t nugapp, const uuid_t datatype,
                              unsigned short nugport, unsigned instances, unsigned nugid,
                              const char *name, unsigned *nuggetid)
{
    //Connect to Dispatch Server
    RZBNetworkConnection *net = ConnectMe(rzbconfig.dsrvaddr, rzbconfig.dsrvport);

    if (!net)
    {
        rzb_log(LOG_ERR, "connection to %s:%s failed", rzbconfig.dsrvaddr, rzbconfig.dsrvport);
        exit(-1);
    }

    //Set up packet format to send
    SNAKECHARMER scpacket;
    REGPACKET regpacket;

    /* Build Preamble Packet */
    protocolFill(&scpacket);
    scpacket.msgtype = REG;
    uuid_copy(scpacket.datatype, nugtype);

    /* Build Registration Packet */
    /* Nugget Network Info */
    inet_pton(AF_INET, rzbconfig.nugaddr, &regpacket.nugaddr);
    regpacket.nugport = nugport;
    regpacket.dummy = 0;

    /* Capability Declaration */
    uuid_copy(regpacket.nugtype, nugtype);
    uuid_copy(regpacket.nugapp, nugapp);
    uuid_copy(regpacket.datatype, datatype);
    regpacket.freeinstances = instances;
    regpacket.nuggetid = nugid;

    /* Nugget Name */
    memset(regpacket.name, 0, sizeof(regpacket.name));
    snprintf(regpacket.name, sizeof(regpacket.name), "%s", name);

    //Send packet
    if (sendWrap(net, &scpacket, sizeof(scpacket)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        return R_FAIL;
    }

    if (sendWrap(net, &regpacket, sizeof(regpacket)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        return R_FAIL;
    }

    //Recv ACK (hopefully)
    if (recvWrap(net, &scpacket, sizeof(scpacket)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        return R_FAIL;
    }

    if (recvWrap(net, nuggetid, sizeof(*nuggetid)) != R_SUCCESS)
    {
        NetworkConnectionDestroy(net);
        rzb_log(LOG_ERR, "No nugget id");
        return R_FAIL;
    }
    NetworkConnectionDestroy(net);
    //Check we got ACK from dispatch server
    //NEEDS WORK:
    //We need to grab a uuid generated by the dispatch server and return it
    //so we can use it in subsequent requests
    switch (scpacket.msgtype)
    {
        case ACK:
            return R_SUCCESS;

        default:
            return R_FAIL;
    }
}

static HRESULT rzbRegisterHandler(handler_fp fp, const uuid_t *acceptedTypes,
                                  size_t numTypes, const uuid_t nuggetType)
{
    size_t i;
    static int hasReged = 0;
    static unsigned nuggetid = 0;

    handlerCount++;

    char uuid_str[SIZE_OF_UUID_STRING];

    // The stub will ignore types, but list what you attempted to register...
    rzb_log(LOG_INFO, "Handler %u accepts the following types:", handlerCount);
    for (i = 0; i < numTypes; i++)
    {
        if (hasReged == 0)
        {
            registerNugget(DETECTION,
                           nuggetType,
                           acceptedTypes[i],
                           strtoul(rzbconfig.nugport, NULL, 10),
                           rzbconfig.maximumthreads,
                           5,
                           rzbconfig.nugname,
                           &nuggetid);
            hasReged = 1;
        }
        else
            updateNugget(DETECTION, nuggetType, acceptedTypes[i], strtoul(rzbconfig.nugport, NULL, 10), nuggetid);
        uuid_unparse(acceptedTypes[i], uuid_str);
        rzb_log(LOG_INFO, "%s", uuid_str);
    }

    if (addHandler(fp) == R_FAIL)
        return R_FAIL;

    head->acceptedTypes = malloc(numTypes * sizeof(uuid_t));
    if (!head->acceptedTypes)
        return R_MALLOC_FAIL;

    memcpy(head->acceptedTypes, acceptedTypes, numTypes * sizeof(uuid_t));
    head->numTypes = numTypes;

    return R_SUCCESS;
}

